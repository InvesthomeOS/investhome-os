function translateString(s) {
  if (typeof s !== 'string') return s;
  if (WORDS[s]) return WORDS[s];
  let out = s;
  for (const [enPhrase, trPhrase] of PHRASES) {
    if (out.includes(enPhrase)) out = out.split(enPhrase).join(trPhrase);
  }
  if (WORDS[out]) return WORDS[out];
  // Multi-word: map each word if all known
  const parts = out.split(' ');
  if (parts.length > 1 && parts.every((p) => WORDS[p] || /^[{}…—',\-/0-9]+$/.test(p) || p.length <= 2)) {
    return parts.map((p) => WORDS[p] ?? p).join(' ');
  }
  return out;
}

function translateTree(node) {
  if (typeof node === 'string') return translateString(node);
  if (Array.isArray(node)) return node.map(translateTree);
  if (node && typeof node === 'object') {
    const out = {};
    for (const [k, v] of Object.entries(node)) out[k] = translateTree(v);
    return out;
  }
  return node;
}

function deepMerge(base, override) {
  if (!override || typeof override !== 'object' || Array.isArray(override)) return override ?? base;
  const out = { ...base };
  for (const [k, v] of Object.entries(override)) {
    if (v && typeof v === 'object' && !Array.isArray(v) && out[k] && typeof out[k] === 'object') {
      out[k] = deepMerge(out[k], v);
    } else {
      out[k] = v;
    }
  }
  return out;
}

