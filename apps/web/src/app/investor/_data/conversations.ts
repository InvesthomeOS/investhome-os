export function getAllConversations(): Conversation[] {
  return conversations.map((c) => ({ ...c, messages: [...c.messages] }));
}

export function getConversationById(id: string): Conversation | undefined {
  const found = conversations.find((c) => c.id === id);
  if (!found) return undefined;
  return { ...found, messages: [...found.messages], timelineEvents: [...found.timelineEvents] };
}

export function getVisibleMessages(conversation: Conversation): Message[] {
  return conversation.messages.filter((m) => !m.isInternal);
}

