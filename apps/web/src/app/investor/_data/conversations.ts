function attach(
  id: string,
  fileName: string,
  fileType: Attachment['fileType'],
  fileSizeBytes: number,
): Attachment {
  return { id, fileName, fileType, fileSizeBytes, isMock: true };
}

function msg(
  partial: Omit<Message, 'isInternal'> & { isInternal?: boolean },
): Message {
  return { isInternal: false, ...partial };
}

function internalNote(
  partial: Omit<Message, 'isInternal' | 'author'> & { author?: MessageAuthor },
): Message {
  return {
    ...partial,
    author: partial.author ?? IR_TEAM.marcus,
    isInternal: true,
  };
}

function timeline(
  id: string,
  type: TimelineEvent['type'],
  title: string,
  description: string,
  timestamp: string,
  referenceId?: string,
): TimelineEvent {
  return { id, type, title, description, timestamp, referenceId };
}

function conv(
  partial: Omit<
    Conversation,
    'messages' | 'timelineEvents'
  > & {
    messages: Message[];
    timelineEvents?: TimelineEvent[];
  },
): Conversation {
  const visibleMessages = partial.messages.filter((m) => !m.isInternal);
  const lastMsg = visibleMessages[visibleMessages.length - 1];
  return {
    ...partial,
    messages: partial.messages,
    timelineEvents: partial.timelineEvents ?? [],
    lastMessagePreview: lastMsg?.body.slice(0, 120) ?? partial.lastMessagePreview,
    lastMessageAt: lastMsg?.sentAt ?? partial.lastMessageAt,
    unreadCount: visibleMessages.filter((m) => !m.isRead && !m.author.isInvestor).length,
    hasAttachments: visibleMessages.some((m) => m.attachments.length > 0),
  };
}

